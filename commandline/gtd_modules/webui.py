def js_data(variable, payload):
    """
    Serialise `payload` as a JS file assigning it to a global.

    Two escapes are applied to the JSON beyond what `json.dumps` does:

      * U+2028/U+2029 — legal in JSON strings but illegal in JavaScript string
        literals before ES2019; cheap insurance for an offline file.
      * `<`, `>`, `&` — emitted as `\\u003c`/`\\u003e`/`\\u0026`. These cannot
        appear in JSON *syntax*, only inside strings, so replacing them keeps the
        document equivalent. It matters because email content is untrusted: a body
        containing a literal `</script>` would break out of a `<script>` element
        if this data were ever inlined into a page. It is loaded as an external
        file today (where HTML parsing does not apply), but escaping here means
        the hazard cannot reappear if that ever changes.

    Example:
        js_data("GTD_MAIL", {"a": "</script>"})
        # -> 'window.GTD_MAIL = {"a": "\\u003c/script\\u003e"};\\n'
    """
    text = json.dumps(payload, ensure_ascii=False, allow_nan=False)
    for char, escaped in (("\u2028", "\\u2028"), ("\u2029", "\\u2029"),
                          ("<", "\\u003c"), (">", "\\u003e"), ("&", "\\u0026")):
        text = text.replace(char, escaped)
    return f"window.{variable} = {text};\n"


def _head(title, layout_css="assets/clearlooks.css", viewport=None,
          extra_scripts=()):
    """
    The shared <head>. theme.css (the colour tokens) always loads before the
    build's layout stylesheet, and settings.js loads synchronously so the saved
    appearance is applied before first paint.
    """
    scripts = "".join(f'\n<script src="{src}"></script>' for src in extra_scripts)
    viewport = viewport or "width=device-width, initial-scale=1"
    return f"""<!DOCTYPE html>
<html lang="en" data-theme="light" data-tone="warm">
<head>
<meta charset="utf-8">
<meta name="viewport" content="{viewport}">
<title>{html.escape(title)}</title>
<link rel="stylesheet" href="assets/theme.css">
<link rel="stylesheet" href="{layout_css}">
<script src="assets/settings.js"></script>{scripts}
</head>
<body>"""


def _toolbar(page):
    """
    The top toolbar. On the mail page it holds the per-message action buttons
    (filled in by app.js), the search box and the sort selector; on the
    performance page only the title and the theme toggle are meaningful.
    """
    if page == "mail":
        sort_options = [("date-desc", "Newest first"), ("date-asc", "Oldest first"),
                        ("due-asc", "Due date (soonest)"),
                        ("due-desc", "Due date (latest)"),
                        ("subject", "Subject"), ("from", "Correspondent"),
                        ("folder", "Folder")]
        options = "".join(f'<option value="{value}">{html.escape(label)}</option>'
                          for value, label in sort_options)
        middle = f"""  <div class="tb-group" id="tb-actions"></div>
  <div class="tb-spacer"></div>
  <label class="search"><input id="search" class="field" type="search"
         placeholder="Search all folders&#8230;" aria-label="Search all folders"></label>
  <select id="sort" aria-label="Sort messages">{options}</select>
"""
    else:
        middle = """  <div class="tb-group"><span class="chip">Performance report</span></div>
  <div class="tb-spacer"></div>
"""
    return f"""<div class="toolbar" role="toolbar">
  <div class="brand">GTD<small>&#183;EML</small></div>
{middle}  <button class="btn" id="settings-button" type="button"
          title="Appearance and fonts">Settings&#8230;</button>
</div>"""


def _sidebar(page, sections, views=(), hashtags=()):
    """
    The left sidebar, in four labelled categories:

        OVERVIEWS     Dashboard, Performance
        IN & OUT      Inbox, Sent          (omitted when no own-accounts)
        DUE & FLAGGED Due date set, Due date not set, Pinned
        HASHTAGS      one per monitored_hashtags entry (omitted when unset)
        GTD STATUS    the six numbered workflow folders, with counts

    On the mail page every entry is a button app.js handles in-page; on the
    performance page they are links back into `index.html`, whose hash selects the
    section. `views` is `site_data["views"]` — empty when `my_own_accounts` is
    unset, in which case IN AND OUT is omitted rather than shown always-empty.

    The DUE & FLAGGED and HASHTAGS badges are left empty for app.js to fill: their
    membership depends on the on-radar folder scope chosen in Settings.
    """
    def entry(key, label, count=None, active=False, live_badge=False):
        if live_badge:
            badge = f'<span class="badge" data-count-for="{html.escape(key)}"></span>'
        else:
            badge = "" if count is None else f'<span class="badge">{count}</span>'
        classes = "nav-item" + (" active" if active else "")
        inner = f'<span class="label">{html.escape(label)}</span>{badge}'
        if page == "mail" and key != "performance":
            return (f'<button class="{classes}" type="button" '
                    f'data-section="{html.escape(key)}">{inner}</button>')
        if key == "performance":
            if page == "performance":
                return f'<span class="{classes}" aria-current="true">{inner}</span>'
            return f'<a class="{classes}" href="{PERFORMANCE_FILE}">{inner}</a>'
        return f'<a class="{classes}" href="{INDEX_FILE}#{html.escape(key)}">{inner}</a>'

    def group(title, items):
        """`title` may contain entities (e.g. &amp;), so it is inserted as-is."""
        body = "\n  ".join(items)
        return f'<div class="group-label">{title}</div>\n  {body}'

    groups = [group("Overviews", [
        entry("overview", HOMEPAGE_LABEL, active=(page == "mail")),
        entry("performance", PERFORMANCE_LABEL, active=(page == "performance")),
    ])]
    if views:
        groups.append(group("In &amp; out",
                            [entry(v["key"], v["label"], v["count"]) for v in views]))
    groups.append(group("Due &amp; flagged",
                        [entry(v["key"], v["label"], live_badge=True)
                         for v in MARKER_VIEWS]))
    if hashtags:
        groups.append(group("Hashtags",
                            [entry(tag["key"], tag["label"], live_badge=True)
                             for tag in hashtags]))
    groups.append(group("GTD status",
                        [entry(section["key"], section["label"], section["count"])
                         for section in sections]))
    body = "\n  ".join(groups)
    return f"""<nav class="sidebar" aria-label="Workflow sections">
  {body}
</nav>"""


def _statusbar(page, site_data):
    """
    The bottom status bar. The first two cells are live on the mail page (app.js
    writes the current mailbox and selection into them); the rest are the same on
    both pages — a standing reminder that this is a report, plus provenance.
    """
    generated = html.escape(site_data.get("generatedAt", ""))
    working = html.escape(site_data.get("workingDirectory", ""))
    if page == "mail":
        left = ('<span class="cell" id="sb-where">Overview</span>\n'
                '  <span class="cell grow mono" id="sb-file">No message selected</span>')
    else:
        counts = site_data.get("overview", {}).get("counts", {})
        left = (f'<span class="cell">Performance</span>\n'
                f'  <span class="cell grow">{counts.get("tracked", 0)} tracked '
                f"email(s) analysed</span>")
    return f"""<div class="statusbar">
  {left}
  <span class="cell ro" title="Nothing here writes to your workflow">READ-ONLY</span>
  <span class="cell">Generated {generated}</span>
  <span class="cell mono" title="working_directory">{working}</span>
</div>"""


